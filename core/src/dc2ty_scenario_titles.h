inline std::string_view dc2ty_scenario_title(std::string_view script) {
    auto lower = [](char value) { return value >= 'A' && value <= 'Z' ? char(value + 'a' - 'A') : value; };
    if (script.size() >= 4 && script[script.size()-4] == '.'
            && lower(script[script.size()-3]) == 'm' && lower(script[script.size()-2]) == 'e'
            && lower(script.back()) == 's') script.remove_suffix(4);
    for (const auto& entry : Dc2TyScenarioTitles) {
        if (entry.script.size() != script.size()) continue;
        bool matches = true;
        for (std::size_t i = 0; i < script.size(); ++i)
            if (entry.script[i] != lower(script[i])) { matches = false; break; }
        if (matches) return entry.title;
    }
    return {};
}

